class Job:
    def __init__(self, name, notebook, code_cell, deck_cell, patch, header,
                 deck_module, deck_title, deck_why):
        self.name = name
        self.notebook = notebook
        self.code_cell = code_cell
        self.deck_cell = deck_cell
        self.patch = patch          # (compiled regex, replacement)
        self.header = header
        self.deck_module = deck_module
        self.deck_title = deck_title
        self.deck_why = deck_why


