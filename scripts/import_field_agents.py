def do(job: Job) -> int:
    nb_path = ROOT / "notebooks" / job.notebook
    if not nb_path.exists():
        print(f"missing {nb_path}", file=sys.stderr)
        return 1
    nb = json.loads(nb_path.read_text(encoding="utf-8"))

    code = "".join(nb["cells"][job.code_cell]["source"])
    code = re.sub(r"^%%writefile main\.py\n", "", code)
    pattern, repl = job.patch
    if not pattern.search(code):
        print(f"{job.name}: deck loader not found -- notebook layout changed",
              file=sys.stderr)
        return 1
    code = pattern.sub(repl, code, count=1)
    if "MY_DECK" not in code:
        print(f"{job.name}: patch did not introduce MY_DECK", file=sys.stderr)
        return 1

    out = SOURCES / f"{job.name}.py"
    out.write_text(job.header + "\n" + code, encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} ({len(code.splitlines())} lines)")

    deck_src = "".join(nb["cells"][job.deck_cell]["source"])
    deck_src = re.sub(r"^%%writefile deck\.csv\n", "", deck_src)
    counts = Counter(int(x) for x in deck_src.split())
    if sum(counts.values()) != 60:
        print(f"{job.name}: deck is {sum(counts.values())} cards, not 60",
              file=sys.stderr)
        return 1

    sys.path.insert(0, str(ROOT))
    try:
        from decks.base import card_table
        names = {cid: (info.name if info else "?")
                 for cid, info in ((c, card_table().get(c)) for c in counts)}
    except Exception:  # noqa: BLE001
        names = {cid: "" for cid in counts}

    lines = "".join(
        f"    {cid}: {n},{' ' * max(1, 6 - len(str(cid)) - len(str(n)))}"
        f"# {names.get(cid, '')}\n".replace(" #  ", " # ")
        for cid, n in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])))
    deck_out = DECKS / f"{job.deck_module}.py"
    deck_out.write_text(DECK_TEMPLATE % {"title": job.deck_title,
                                         "why": job.deck_why,
                                         "lines": lines}, encoding="utf-8")
    print(f"wrote {deck_out.relative_to(ROOT)} "
          f"({len(counts)} distinct, 60 cards)")
    return 0


def main() -> int:
    rc = 0
    for job in JOBS:
        rc |= do(job)
    print("\nregistered names (agents/agentkit/rulebased/__init__.py):")
    for job in JOBS:
        print(f'    "{job.name}": "{job.deck_module}",')
    print("\nthen, per anchor:\n"
          "  python -X utf8 scripts/arena.py play bc rule:alakazam5 "
          "--deck-a grimmsnarl --deck-b alakazam5 --matches 1000")
    return rc


if __name__ == "__main__":
    sys.exit(main())
